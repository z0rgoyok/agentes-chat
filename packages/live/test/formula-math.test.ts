describe("operators", () => {
  test.each(OPERATORS)("%s", (formula, expected) => same(ev(formula), expected));
});

describe("math", () => {
  test.each(MATH)("%s", (formula, expected) => same(ev(formula), expected));

  test("RAND and RANDBETWEEN stay put and stay in range", () => {
    const r = ev("=RAND()") as number;
    expect(r).toBeGreaterThanOrEqual(0);
    expect(r).toBeLessThan(1);
    expect(ev("=RAND()")).toBe(r);
    const n = ev("=RANDBETWEEN(1,6)") as number;
    expect(Number.isInteger(n) && n >= 1 && n <= 6).toBe(true);
    expect(ev("=RANDBETWEEN(5,1)")).toEqual(err("#NUM!"));
    // Two draws in one formula differ.
    expect(ev("=RAND()=RAND()")).toBe(false);
  });

  test("SUBTOTAL leaves out other subtotals in its range", () => {
    const b = book(["Sheet1"], { rows: 10, cols: 4 });
    putAll(b, { A1: 1, A2: 2, A3: "=SUBTOTAL(9,A1:A2)", A4: 4, A5: "=SUBTOTAL(9,A1:A4)", A6: "=SUM(A1:A4)" });
    expect(val(b, "A5")).toBe(7);
    expect(val(b, "A6")).toBe(10);
  });
});

describe("statistics", () => {
  test.each(STATS)("%s", (formula, expected) => same(ev(formula), expected));

  test("criteria with dates, numbers as text and empty cells", () => {
    const b = book(["Sheet1"], { rows: 10, cols: 4 });
    putAll(b, { A1: 46343, A2: 46344, A3: "10", A4: 10, B1: '=COUNTIF(A1:A4,">=46344")', B2: "=COUNTIF(A1:A4,10)" });
    put(b, "B3", '=COUNTIF(A1:A4,">5")');
    expect(val(b, "B1")).toBe(1);
    // A criterion's number matches numbers and numeric text; comparisons only numbers.
    expect(val(b, "B2")).toBe(2);
    expect(val(b, "B3")).toBe(3);
  });
});
