/**
 * Writes `apps/mobile/src/ui/icons.material.data.ts`: the path data of the Google symbols the phone app draws on
 * Android (`icons.material.names.ts`), outline and filled, from the `@material-symbols/svg-600` npm package (Material
 * Symbols, Rounded, Apache License 2.0). Only the symbols the app names go in, so the app carries about a hundred
 * symbols rather than the whole set. The package is not a dependency of the repository; install it anywhere and pass
 * its folder:
 *
 *   bun add @material-symbols/svg-600   (in a scratch folder)
 *   bun scripts/material-icons.ts <scratch>/node_modules/@material-symbols/svg-600
 *
 * Weight 600 at the package's 48 optical size: its strokes come to 2 points on a 24-point icon, the weight of the
 * system's own icons at that size (weight 400 drawn for 24).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MATERIAL_NAMES, TAB_MATERIAL } from "../apps/mobile/src/ui/icons.material.names";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: bun scripts/material-icons.ts <path to @material-symbols/svg-600>");
  process.exit(1);
}
const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { name: string; version: string };

/** Every path of a symbol's SVG, as one path's data (they are filled shapes in one color). */
function pathOf(file: string): string {
  const svg = readFileSync(join(dir, "rounded", file), "utf8");
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${file}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${file}: no path`);
  return paths.join("");
}

const names = [
  ...new Set([...Object.values(MATERIAL_NAMES), ...Object.values(TAB_MATERIAL)].filter((n): n is string => n !== null)),
].sort();
const entries = names.map((name) => {
  const line = pathOf(`${name}.svg`);
  let fill: string;
  try {
    fill = pathOf(`${name}-fill.svg`);
  } catch {
    fill = line;
  }
  return `  ${JSON.stringify(name)}: { line: ${JSON.stringify(line)}, fill: ${JSON.stringify(fill)} },`;
});

const out = `/**
 * Generated by scripts/material-icons.ts from ${pkg.name} ${pkg.version}; do not edit. Regenerate after changing
 * icons.material.names.ts.
 *
 * Material Symbols (Rounded), Copyright Google LLC, licensed under the Apache License, Version 2.0
 * (apps/mobile/src/ui/LICENSE.material-symbols; NOTICE). Changed from the package's files: each symbol's SVG is reduced
 * to its path data (a symbol's paths joined into one), outline (\`line\`) and filled (\`fill\`), on the symbols' own
 * grid (viewBox "0 -960 960 960").
 */
export const MATERIAL_PATHS: Record<string, { line: string; fill: string }> = {
${entries.join("\n")}
};
`;
writeFileSync(join(import.meta.dir, "../apps/mobile/src/ui/icons.material.data.ts"), out);
console.log(`${names.length} symbols`);
